def _elf64(e_type: int, machine: int = 183, extra: str = "") -> bytes:
    """Minimal but structurally plausible ELF64 (e_type 2=EXEC, 3=DYN/PIE)."""
    e_phnum = 1
    e_phentsize = 56
    e_phoff = 64
    header = bytearray(64)
    header[0:4] = b"\x7fELF"
    header[4] = 2
    header[5] = 1
    header[6] = 1
    struct.pack_into("<HH", header, 16, e_type, machine)          # e_type,e_machine
    struct.pack_into("<I", header, 20, 1)                          # e_version
    struct.pack_into("<QQQ", header, 24, 0, e_phoff, 0)            # entry, phoff, shoff
    struct.pack_into("<I", header, 48, 0)                          # e_flags
    struct.pack_into("<H", header, 52, 64)                         # ehsize
    struct.pack_into("<H", header, 54, e_phentsize)                # e_phentsize
    struct.pack_into("<H", header, 56, e_phnum)                    # e_phnum
    struct.pack_into("<H", header, 58, 0)                          # e_shentsize
    struct.pack_into("<H", header, 60, 0)                          # e_shnum
    struct.pack_into("<H", header, 62, 0)                          # e_shstrndx
    # one GNU_STACK program header (RW, non-executive)
    ph = bytearray(e_phentsize)
    struct.pack_into("<IQQQQQQ", ph, 0,
                     0x6474E551,   # p_type PT_GNU_STACK
                     6,            # p_flags RW
                     0, 0, 0, 0, 0)
    blob = bytes(header) + bytes(ph)
    blob += b"\x00Lcom/example/insecurebank/Native;\x00"
    for text in (
        "app-private-secret-key-athlete-customers",
        "AES/ECB/NoPadding",
        extra,
    ):
        if text:
            blob += text.encode("ascii", "replace") + b"\n"
    return blob


