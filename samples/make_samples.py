def _wipe(path: str) -> None:
    if os.path.isdir(path):
        shutil.rmtree(path)
    os.makedirs(path, exist_ok=True)


def _write(path: str, data, binary: bool = False) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    mode = "wb" if binary else "w"
    with open(path, mode) as fh:
        fh.write(data)


def build_android_tree() -> None:
    _wipe(ANDROID_ROOT)
    main = os.path.join(ANDROID_ROOT, "app", "src", "main")
    pkg_dir = os.path.join(main, "java", "com", "example", "insecurebank")
    res_xml = os.path.join(ANDROID_ROOT, "res", "xml")
    assets = os.path.join(ANDROID_ROOT, "assets")
    values = os.path.join(ANDROID_ROOT, "res", "values")
    outputs = os.path.join(ANDROID_ROOT, "build", "outputs")
    dex_dir = os.path.join(ANDROID_ROOT, "app", "build", "intermediates")

    application_body = (
        '    <activity android:name="com.example.insecurebank.LoginActivity"\n'
        '        android:exported="true">\n'
        "        <intent-filter>\n"
        '            <action android:name="android.intent.action.MAIN" />\n'
        '            <category android:name="android.intent.category.LAUNCHER" />\n'
        "        </intent-filter>\n"
        "    </activity>\n"
        '    <activity android:name="com.example.insecurebank.PinActivity"\n'
        '        android:exported="true" />\n'
        '    <service android:name="com.example.insecurebank.SyncService"\n'
        '        android:exported="true" />\n'
        '    <provider android:name="com.example.insecurebank.CredentialsProvider"\n'
        '        android:authorities="com.example.insecurebank.credentials"\n'
        '        android:exported="true"\n'
        '        android:grantUriPermissions="true" />\n'
        '    <receiver android:name="com.example.insecurebank.PushReceiver"\n'
        '        android:exported="true" />\n'
        '    <activity android:name="com.example.insecurebank.PrivateNotes"\n'
        '        android:exported="false" />\n'
    )

    manifest_xml = manifest_plain(
        package=ANDROID_PACKAGE,
        version="2.3.1",
        min_sdk=16,
        target_sdk=28,
        debuggable=True,
        allow_backup=True,
        cleartext=True,
        uses_permissions=(
            "android.permission.INTERNET",
            "android.permission.ACCESS_NETWORK_STATE",
            "android.permission.READ_SMS",
            "android.permission.CAMERA",
            "android.permission.ACCESS_FINE_LOCATION",
            "android.permission.READ_EXTERNAL_STORAGE",
            "android.permission.WRITE_EXTERNAL_STORAGE",
            "android.permission.SET_DEBUG_APP",
        ),
        body=application_body,
    )
    _write(os.path.join(main, "AndroidManifest.xml"), manifest_xml.decode("utf-8"))
    _write(os.path.join(res_xml, "network_security_config.xml"),
           NSC_CLEARTEXT.decode("utf-8"))
    _write(os.path.join(values, "strings.xml"),
           XML_STRINGS)
    _write(os.path.join(assets, "config.properties"), ASSET_CONFIG)

    for name, text in JAVA_SOURCES.items():
        _write(os.path.join(pkg_dir, name), text)

    _write(os.path.join(dex_dir, "classes.dex"), bank_dex(), binary=True)

    # native fixtures: a hardened (PIE) image and a deliberately non-PIE one
    lib_dir = os.path.join(ANDROID_ROOT, "app", "src", "main", "jniLibs")
    _write(os.path.join(lib_dir, "arm64-v8a", "libcrypto-hardened.so"),
           _elf64(e_type=3), binary=True)
    _write(os.path.join(lib_dir, "armeabi-v7a", "liblegacy.so"),
           _elf64(e_type=2), binary=True)

    # the embedded release-style APK
    apk_path = os.path.join(outputs, "InsecureBank.apk")
    os.makedirs(outputs, exist_ok=True)
    with zipfile.ZipFile(apk_path, "w") as z:
        z.writestr("AndroidManifest.xml", manifest_axml(ANDROID_PACKAGE, "2.3.1"))
        z.writestr("classes.dex", bank_dex())
        z.writestr("res/xml/network_security_config.xml", NSC_CLEARTEXT)
        z.writestr("lib/arm64-v8a/libcrypto-hardened.so", _elf64(e_type=3))
        z.writestr("lib/armeabi-v7a/liblegacy.so", _elf64(e_type=2))
    _write(os.path.join(ANDROID_ROOT, "README.txt"), ANDROID_README)


