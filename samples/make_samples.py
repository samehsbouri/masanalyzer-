def build_ios_tree() -> None:
    _wipe(IOS_ROOT)
    app = os.path.join(IOS_ROOT, "Payload", "InsecureNotes.app")
    sources = os.path.join(IOS_ROOT, "Sources")
    outputs = os.path.join(IOS_ROOT, "build", "outputs")

    info = dump_bplist({
        "CFBundleIdentifier": IOS_PACKAGE,
        "CFBundleName": "InsecureNotes",
        "CFBundleDisplayName": "InsecureNotes",
        "CFBundleExecutable": "InsecureNotes",
        "CFBundleShortVersionString": "1.4.2",
        "CFBundleVersion": "42",
        "MinimumOSVersion": "11.0",
        "NSAppTransportSecurity": {"NSAllowsArbitraryLoads": True},
    })
    prefs = dump_bplist({
        "username": "admin",
        "password": "changeme123",
        "authToken": "eyJhbGciOiJIUzI1NiJ9.fixturesignature",
        "highlightColor": "#33FF88",
        "user_email": "fixtures@example.net",
        "last_sync": "2026-01-01T00:00:00Z",
    })
    macho = build_macho(
        symbols=("_debug_helper_doLogin", "_helper_keychainRemoveShared"),
        suffix_strings=(
            "https://syncserver.example.net/cache?",
            "password=%@&pin=%@",
            "AES/ECB/NoPadding",
        ),
    )
    profile = build_mobileprovision(
        get_task_allow=True, name="InsecureNotes DevProfile"
    )

    _write(os.path.join(app, "Info.plist"), info, binary=True)
    _write(os.path.join(app, "Prefs.plist"), prefs, binary=True)
    _write(os.path.join(app, "InsecureNotes"), macho, binary=True)
    _write(os.path.join(app, "embedded.mobileprovision"), profile, binary=True)
    for name, text in SWIFT_SOURCES.items():
        _write(os.path.join(sources, name), text)

    ipa_path = os.path.join(outputs, "InsecureNotes.ipa")
    os.makedirs(outputs, exist_ok=True)
    with zipfile.ZipFile(ipa_path, "w") as z:
        z.writestr("Payload/InsecureNotes.app/Info.plist", info)
        z.writestr("Payload/InsecureNotes.app/Prefs.plist", prefs)
        z.writestr("Payload/InsecureNotes.app/InsecureNotes", macho)
        z.writestr("Payload/InsecureNotes.app/embedded.mobileprovision", profile)
    _write(os.path.join(IOS_ROOT, "README.txt"), IOS_README)


def main() -> None:
    build_android_tree()
    build_ios_tree()
    out = os.path.join(HERE, "out")
    os.makedirs(out, exist_ok=True)
    open(os.path.join(out, ".gitkeep"), "a").close()
    files = []
    for root in (ANDROID_ROOT, IOS_ROOT):
        files.extend(os.path.join(dirpath, fn)
                     for dirpath, _, names in os.walk(root)
                     for fn in names)
    print(f"samples rebuilt: {len(files)} files under samples/")
    return None


if __name__ == "__main__":
    main()
